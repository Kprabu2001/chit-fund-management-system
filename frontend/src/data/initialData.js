export const classifyTier = (amount) => {
  const val = Number(amount);
  if (isNaN(val) || val < 25000 || val > 1000000) {
    return null;
  }
  if (val >= 25000 && val <= 50000) return 'starter';
  if (val > 50000 && val <= 100000) return 'bronze';
  if (val > 100000 && val <= 200000) return 'silver';
  if (val > 200000 && val <= 500000) return 'gold';
  if (val > 500000 && val <= 1000000) return 'diamond';
  return null;
};

